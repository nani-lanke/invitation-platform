"""Builds the web assets and registry for the optional "Redesigned Collection".

Reads the finished redesign in redesign-100/ (manifest + cards/<slug>/ +
output/png/) and writes, without touching any existing file:
  images/redesign-100/<slug>/  venue.webp crest.webp corner-tl.webp corner-tr.webp footer.webp thumb.jpg
  js/redesign-collection-data.js  (the collection registry, IH.REDESIGN_COLLECTION_DATA)
Usage: python scripts/build-redesign-collection.py
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RD = os.path.join(ROOT, 'redesign-100')
OUT = os.path.join(ROOT, 'images', 'redesign-100')
GROUPS = [  # catalogue index ranges of the selection (see redesign-100/work/briefs.js)
    ('regional', 'Indian Regional & Heritage', 1, 40),
    ('rituals', 'Rituals, Faith & Pre-wedding', 41, 63),
    ('royal', 'Royal Luxury', 64, 76),
    ('south-asian', 'South Asian', 77, 79),
    ('botanical', 'Botanical & Destination', 80, 100),
]


def fit(im, max_w):
    if im.width > max_w:
        im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
    return im


manifest = json.load(open(os.path.join(RD, 'output', 'manifest.json'), encoding='utf8'))
selected = sorted((i for i in manifest['invitations'] if i['status'] == 'SELECTED_FOR_REDESIGN'), key=lambda i: i['index'])
assert len(selected) == 100, len(selected)
cards = []
for inv in selected:
    slug, src = inv['slug'], os.path.join(RD, 'cards', inv['slug'])
    dst = os.path.join(OUT, slug)
    os.makedirs(dst, exist_ok=True)
    fit(Image.open(os.path.join(src, 'venue.jpg')).convert('RGB'), 960).save(os.path.join(dst, 'venue.webp'), quality=82, method=6)
    fit(Image.open(os.path.join(src, 'footer.jpg')).convert('RGB'), 1000).save(os.path.join(dst, 'footer.webp'), quality=80, method=6)
    fit(Image.open(os.path.join(src, 'crest.png')).convert('RGBA'), 420).save(os.path.join(dst, 'crest.webp'), quality=86, method=6)
    corners = os.path.exists(os.path.join(src, 'corner-tl.png'))
    if corners:
        for c in ('corner-tl', 'corner-tr'):
            fit(Image.open(os.path.join(src, c + '.png')).convert('RGBA'), 420).save(os.path.join(dst, c + '.webp'), quality=86, method=6)
    # Gallery thumbnail: the top 3:4 of the validated full-card render.
    png = Image.open(os.path.join(RD, inv['render']['png'].replace('redesign-100/', ''))).convert('RGB')
    png.crop((0, 0, png.width, round(png.width * 4 / 3))).resize((600, 800), Image.LANCZOS).save(os.path.join(dst, 'thumb.jpg'), quality=85, optimize=True)
    group = next(g for g in GROUPS if g[2] <= inv['index'] <= g[3])
    cards.append({'slug': 'rd-' + slug, 'base': slug, 'index': inv['index'], 'group': group[0], 'corners': corners})

data = {
    'id': 'redesign-100',
    'label': 'Redesigned Collection',
    'version': manifest['generated'][:10],
    'groups': [{'id': g[0], 'label': g[1]} for g in GROUPS],
    'cards': cards,
}
with open(os.path.join(ROOT, 'js', 'redesign-collection-data.js'), 'w', encoding='utf8') as fh:
    fh.write('/* Generated by scripts/build-redesign-collection.py from redesign-100/output/manifest.json. Do not edit by hand. */\n')
    fh.write('window.IH = window.IH || {};\nwindow.IH.REDESIGN_COLLECTION_DATA = ' + json.dumps(data, indent=1) + ';\n')
total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(OUT) for f in fs)
print('cards', len(cards), 'assets MB', round(total / 1e6, 1))
